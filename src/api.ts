import { invoke } from "@tauri-apps/api/core";
import { Character, Group, GroupMessage, Memory, Mood, Settings, StoredMessage, Template } from "./types";
import { ageRuleError } from "./protect";

export const api = {
  listCharacters: () => invoke<Character[]>("list_characters"),
  /** Every save goes through the protect rule: under 18 only as family. */
  saveCharacter: (character: Character) => { const bad = ageRuleError(character); return bad ? Promise.reject(new Error(bad)) : invoke<Character>("save_character", { character }); },
  deleteCharacter: (id: string) => invoke<void>("delete_character", { id }),
  listMessages: (characterId: string) => invoke<StoredMessage[]>("list_messages", { characterId }),
  addMessage: (characterId: string, role: "user" | "assistant", content: string, isError = false) =>
    invoke<StoredMessage>("add_message", { characterId, role, content, isError }),
  addProactiveMessage: (characterId: string, content: string) => invoke<StoredMessage>("add_proactive_message", { characterId, content }),
  recentMessages: (characterId: string, limit: number) => invoke<StoredMessage[]>("recent_messages", { characterId, limit }),
  markRead: (characterId: string) => invoke<void>("mark_read", { characterId }),
  unreadCounts: () => invoke<Record<string, number>>("unread_counts"),
  setMood: (id: string, mood: Mood, closeness: number, personalMessage?: string | null) =>
    invoke<Character>("set_mood", { id, mood, closeness, personalMessage: personalMessage ?? null }),
  setSummarizedUpto: (id: string, messageId: number) => invoke<void>("set_summarized_upto", { id, messageId }),
  listMemories: (characterId: string) => invoke<Memory[]>("list_memories", { characterId }),
  addMemory: (characterId: string, content: string, pinned = false, source = "") => invoke<Memory | null>("add_memory", { characterId, content, pinned, source }),
  groupSummaryUpto: (groupId: string, characterId: string) => invoke<number>("group_summary_upto", { groupId, characterId }),
  setGroupSummaryUpto: (groupId: string, characterId: string, upto: number) => invoke<void>("set_group_summary_upto", { groupId, characterId, upto }),
  updateMemory: (id: number, content: string, pinned: boolean) => invoke<void>("update_memory", { id, content, pinned }),
  deleteMemory: (id: number) => invoke<void>("delete_memory", { id }),
  ollamaJson: (model: string, messages: { role: string; content: string }[], temperature?: number, opts?: { seed?: number; topP?: number }) => invoke<string>("ollama_json", { model, messages, temperature: temperature ?? null, seed: opts?.seed ?? null, topP: opts?.topP ?? null }),
  listGroups: () => invoke<Group[]>("list_groups"),
  saveGroup: (group: Group) => invoke<Group>("save_group", { group }),
  deleteGroup: (id: string) => invoke<void>("delete_group", { id }),
  listGroupMessages: (groupId: string) => invoke<GroupMessage[]>("list_group_messages", { groupId }),
  addGroupMessage: (groupId: string, speakerId: string | null, content: string, isError = false) =>
    invoke<GroupMessage>("add_group_message", { groupId, speakerId, content, isError }),
  clearGroupMessages: (groupId: string) => invoke<void>("clear_group_messages", { groupId }),
  setReaction: (id: number, reaction: string) => invoke<void>("set_reaction", { id, reaction }),
  updateMessage: (id: number, content: string, alternates: string[] = [], altIndex = 0) => invoke<StoredMessage>("update_message", { id, content, alternates, altIndex }),
  deleteMessage: (id: number) => invoke<void>("delete_message", { id }),
  deleteMessagesAfter: (characterId: string, id: number) => invoke<number>("delete_messages_after", { characterId, id }),
  setGroupReaction: (id: number, reaction: string, reactorId: string | null) => invoke<void>("set_group_reaction", { id, reaction, reactorId }),
  updateGroupMessage: (id: number, content: string, alternates: string[] = [], altIndex = 0) => invoke<GroupMessage>("update_group_message", { id, content, alternates, altIndex }),
  deleteGroupMessage: (id: number) => invoke<void>("delete_group_message", { id }),
  deleteGroupMessagesAfter: (groupId: string, id: number) => invoke<number>("delete_group_messages_after", { groupId, id }),
  listTemplates: () => invoke<Template[]>("list_templates"),
  saveTemplate: (name: string, data: Partial<Character>) => invoke<Template>("save_template", { name, data }),
  deleteTemplate: (id: number) => invoke<void>("delete_template", { id }),
  setTrayTooltip: (text: string) => invoke<void>("set_tray_tooltip", { text }),
  showMainWindow: () => invoke<void>("show_main_window"),
  clearMessages: (characterId: string) => invoke<void>("clear_messages", { characterId }),
  getSettings: () => invoke<Settings>("get_settings"),
  saveSettings: (settings: Settings) => invoke<void>("save_settings", { settings }),
  importAvatar: (srcPath: string) => invoke<string>("import_avatar", { srcPath }),
  avatarDataUrl: (path: string) => invoke<string>("avatar_data_url", { path }),
  setMessageImage: (id: number, path: string | null) => invoke<void>("set_message_image", { id, path }),
  setGroupMessageImage: (id: number, path: string | null) => invoke<void>("set_group_message_image", { id, path }),
  exportImage: (src: string, dest: string) => invoke<void>("export_image", { src, dest }),
  exportCharacter: (id: string, path: string) => invoke<void>("export_character", { id, path }),
  importCharacter: (path: string) => invoke<Character>("import_character", { path }),
  dataDir: () => invoke<string>("data_dir"),
};
